"""Кнопки бота: меню под полем ввода, кнопки под сообщениями и список команд для меню «/».

Кнопка под сообщением отправляет боту команду так же, как если бы вы её напечатали.
Команда без «+» в начале заменяет сообщение с кнопкой (панель обновляется на месте),
с «+» — приходит отдельным сообщением (так кнопка под уведомлением не стирает само уведомление).
"""
from __future__ import annotations

from dataclasses import dataclass

Button = tuple[str, str]  # (надпись, команда)


@dataclass(frozen=True)
class Reply:
    """Ответ на команду: текст и ряды кнопок под ним."""

    text: str
    buttons: tuple[tuple[Button, ...], ...] = ()


def reply_text(reply: str | Reply | None) -> str:
    if reply is None:
        return ""
    return reply if isinstance(reply, str) else reply.text


# Меню под полем ввода: надпись кнопки -> команда
